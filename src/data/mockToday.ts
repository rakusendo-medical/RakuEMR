// モックデータ全体の基準日（＝画面上の「当日」）の単一ソース。
//
// 背景: 以前は「当日」の定義が feature ごとに独立して存在し（2026-02-24 / 03-10 /
// 04-21 / 05-02 / 05-19 の 5 系統）、画面によって数か月ずれたデータが表示されていた。
// 2026-08-24 を基準日として全系統を統一し、以後は本定数を単一ソースとする。
//
// 日付をまとめて動かすとき（デモ用に「直近」へ寄せ直すとき）の決め事:
//   1. **基準日は必ず実日付より過去に置く**。実日付と同日にすると未来日入力抑止が
//      その日の残り時間帯に作動し、モックの当日分が入力できなくなる（E2E も実行時刻依存になる）。
//   2. 平行移動のオフセットは **7 の倍数** にすると曜日が保たれ、曜日をハードコードしている
//      データ（フローシート 7 日固定モックの weekday／診療録タイムラインの dayOfWeek）を
//      直さずに済む。7 の倍数にできない場合はそれらの曜日を再計算すること。
//
// 注意: 改定履歴（src/data/revisions.ts）とコード内コメントの日付は実日付なので動かさない。
export const MOCK_TODAY = '2026-08-24'; // 月曜
